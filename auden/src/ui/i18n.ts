export const dictionaries: Record<Locale, Record<DictKey, string>> = { ru, en };

export function translate(locale: Locale, key: DictKey): string {
  return dictionaries[locale][key] ?? dictionaries.ru[key] ?? key;
}

export function errorText(locale: Locale, code: string | undefined): string {
  const key = `err.${code}` as DictKey;
  return key in ru ? translate(locale, key) : translate(locale, "err.generic");
}
